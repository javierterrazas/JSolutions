    pg.evaluate("ir('obras')"); pg.wait_for_timeout(150)
    ok('Piso de cemento' in pg.evaluate("[...document.querySelectorAll('#bAreas select option')].map(o=>o.value).join('|')"), 'el alta de obra ya lo ofrece para cada espacio')
    pg.click('header .idioma'); pg.evaluate("ir('catalogo')"); pg.wait_for_timeout(250)
    txt = pg.evaluate("document.getElementById('cardTipo').textContent")
    ok('Start from scratch' in txt and 'Tasks (one per line)' in txt and 'Create type' in txt, 'en inglés: "Start from scratch", "Tasks (one per line)", "Create type"')
    b.close()
