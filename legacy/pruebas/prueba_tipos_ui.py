    pg.click('text=+ Nuevo punto de control'); pg.wait_for_timeout(150)
    pg.fill('#hNom','PC6 Pre-sellado'); pg.fill('#hPunto','Superficie sin polvo ni humedad')
    pg.click('#formCat button:has-text("Crear")'); pg.wait_for_timeout(700)
