import sys; sys.path.insert(0,'/tmp'); from navegador import *
fallas=0
def ok(c,m):
    global fallas; print(('  ✓ ' if c else '  ✗ ')+m); fallas += (0 if c else 1)
with sync_playwright() as pw:
    b, pg = abrir(pw, 'Dueno.html', 'du', idioma='es')
    pg.fill('#lEmail','javier'); pg.fill('#lPin','482915'); pg.evaluate("entrar()"); pg.wait_for_timeout(500)
    pg.evaluate("ir('catalogo')"); pg.wait_for_timeout(200)
    ok(pg.is_visible('#tNom') and pg.is_visible('#tPart'), 'Catálogo → "Nuevo tipo de obra" abre en blanco por defecto')
    pg.fill('#tNom','Piso de cemento'); pg.fill('#tPeso','40')
    pg.fill('#tPart','Protección y preparación de superficie\nReparación de grietas\nDesbaste y pulido\nAplicación de sellador')
